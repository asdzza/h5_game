// 教学节奏（11-07 调整：原第 1、2 关合并，原第 3 关前移，新第 3 关做“借它停车”）：
//  1 碰一下   —— 拖动 + 滑到底 + 同色对撞；异色挡路，但挡路者自己也是一对（par 2，上限 6）
//  2 停在墙边 —— 墙也是刹车：停下的位置可以被设计（par 3，上限 5）
//  3 借它停车 —— 挡路的方块也能当刹车，而且停车位是自己推出来的；不推它就要多走一步（par 4，上限 6）
//  4 只要红色 —— 第一次换目标：不用清空，只清红色。两块蓝就是解法本身：一块被推开让路、又当两次刹车；
//                 清空全场要 6 步，上限只有 5 步，所以“清空”这条路根本走不通（par 4，上限 5）
//  5 红色两对 —— 目标色第一次有 4 块（两对）：谁跟谁配成一对由玩家自己定，蓝块和绿块各当一次刹车。
//                 “清空”在这关物理上不可能（蓝绿各只有一块，永远消不掉）（par 4，上限 6）
//  6 双通道   —— 第一次用墙把棋盘切成左右两条竖井，只在第一行和第五行留出口。三对颜色各有
//                 一块在左、一块在右：必须先想好每一对从哪条通道绕过去。先动右上的 B 会把它
//                 的停车位弄丢，代价是多走一步（par 6，上限 10）
//  7 借墙停车 —— 两格墙第一次横在棋盘中间：方块不是停在边框，而是停在半路。B 借上面那格墙停住
//                 自己、消掉后给 A 让出竖线；A 借下面那格墙停到 C 的正上方，消掉后又给 C 让出
//                 竖线。三对刚好串成 B→A→C 一条链（par 5，上限 8）
//  8 小结·三对 —— S1 收尾：两格墙改成对角，第三对第一次借“别的方块”停车，而不是借墙。
//                 C 借 A 停车，A 之后还要被消掉；B 挡住 A 的启动路线，C 又挡住 B 的下落路线，
//                 三对串成 C→B→A 的强制顺序（par 6，上限 9）
//
// S2 几何（第 9 关起）：墙从“刹车”变成“路障”，问题从“停在哪”变成“从哪绕”。
//  9 缺口     —— 两格墙把第 2 列切成两段，只留 (2,2) 一个缺口；左列成了竖井，
//                 C 要让另一块从墙下面绕到第四行来会合。8 块 4 色（par 7，上限 10）
// 10 回廊     —— 三格墙围出回廊：C 借 (2,2) 墙停在第三行，B 借 A 停在 (1,3)、
//                 再借 (4,3) 墙停到第三行；两次墙停 + 一次借块停车（par 6，上限 9）
// 11 窄门     —— 一整列墙只留 (3,3) 一个缺口：右半场的 B 先借墙停在 (4,4)，
//                 给 A 当刹车；A 再穿过缺口到左半场和同伴会合（par 6，上限 9）
// 12 三色台阶 —— 两格墙横在第二行：B 借 A 停在 (1,3) 后落到底行，C 借 (2,2) 墙停在 (3,2)；
//                 三种颜色各走一条路（par 6，上限 9）
//
// 难度不靠“加颜色 / 加墙 / 加尺寸”，而靠：目标是否要换、先后顺序是否耦合、
// 停靠点是否要算准、容错步数是否收紧。颜色与墙只是空间复杂度，放在 S2 之后再当调味。

