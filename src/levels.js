//  4 只要红色 —— 第一次换目标：不用清空，只清红色。两块蓝就是解法本身：一块被推开让路、又当两次刹车；
//                 清空全场要 6 步，上限只有 5 步，所以“清空”这条路根本走不通（par 4，上限 5）
//  5 红色两对 —— 目标色第一次有 4 块（两对）：谁跟谁配成一对由玩家自己定，蓝块和绿块各当一次刹车。
//                 “清空”在这关物理上不可能（蓝绿各只有一块，永远消不掉）（par 4，上限 6）
//  6 双通道   —— 第一次用墙把棋盘切成左右两条竖井，只在第一行和第五行留出口。三对颜色各有
//                 一块在左、一块在右：必须先想好每一对从哪条通道绕过去。先动右上的 B 会把它
//                 的停车位弄丢，代价是多走一步（par 6，上限 10）
//  7 借墙停车 —— 两格墙第一次横在棋盘中间：方块不是停在边框，而是停在半路。B 借上面那格墙停住
//                 自己、消掉后给 A 让出竖线；A 借下面那格墙停到 C 的正上方，消掉后又给 C 让出
//                 竖线。三对刚好串成 B→A→C 一条链（par 5，上限 8）
//  8 小结·三对 —— S1 收尾：两格墙改成对角，第三对第一次借“别的方块”停车，而不是借墙。
//                 C 借 A 停车，A 之后还要被消掉；B 挡住 A 的启动路线，C 又挡住 B 的下落路线，
//                 三对串成 C→B→A 的强制顺序（par 6，上限 9）
