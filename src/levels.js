// 12 三色台阶 —— 两格墙横在第二行：B 借 A 停在 (1,3) 后落到底行，C 借 (2,2) 墙停在 (3,2)；
//                 三种颜色各走一条路（par 6，上限 9）
// 13 对角     —— 两格墙竖在第二列，把棋盘切成上下两段：绿块先贴墙停在 (3,3)，
